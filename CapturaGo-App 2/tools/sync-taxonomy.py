"""Copies the category lists from the website's taxonomy.js into the app.
Usage:  python3 tools/sync-taxonomy.py /path/to/website/taxonomy.js"""
import sys, re, os
src = open(sys.argv[1]).read()
def block(name):
    i = src.index(f'const {name} = [')
    j = src.index('];', i) + 2
    return src[i:j]
out = ['// GENERATED by tools/sync-taxonomy.py from the website\'s taxonomy.js — do not edit by hand.',
       '// Keeps the app and website categories identical.',
       '',
       "export type Group = 'onsite' | 'remote';",
       'export interface Service { id: string; group: Group; icon: string; label: string; short: string; kw: string[] }',
       'export interface Vibe { id: string; icon: string; label: string; kw: string[] }',
       'export interface Occasion { id: string; icon: string; label: string; blurb: string; kw: string[] }',
       '']
for name, typ in [('services', 'Service'), ('vibes', 'Vibe'), ('occasions', 'Occasion')]:
    b = block(name).replace(f'const {name} = [', f'export const {name}: {typ}[] = [', 1)
    out.append(b); out.append('')
dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'lib', 'taxonomy-data.ts')
open(dest, 'w').write('\n'.join(out))
print('wrote', dest)
