"""Copies the Privacy Policy and Terms from the website into the app, so the app shows them natively.
Usage:  python3 tools/sync-legal.py /path/to/website
Writes src/lib/legal-data.ts. Re-run whenever privacy.html or terms.html change."""
import html, json, os, re, sys
from html.parser import HTMLParser

class Legal(HTMLParser):
    """Turns <main class="legal"> into a flat list of blocks: h1, updated, h2, h3, p, li, callout, row."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks, self.inside, self.depth = [], False, 0
        self.cur = None          # (kind, [text parts])
        self.row = None          # list of cells for <tr>
        self.cell = None
        self.callout_depth = None

    def start(self, kind):
        self.flush()
        self.cur = (kind, [])

    def flush(self):
        if self.cur:
            kind, parts = self.cur
            text = re.sub(r'[ \t\r\f\v]+', ' ', ''.join(parts))
            text = re.sub(r' *\n *', '\n', text).strip()
            if text:
                self.blocks.append({'t': kind, 'text': text})
        self.cur = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == 'main' and 'legal' in (a.get('class') or ''):
            self.inside = True
            return
        if not self.inside:
            return
        cls = a.get('class') or ''
        if tag == 'div' and 'callout' in cls:
            self.start('callout'); self.callout_depth = 1; return
        if tag == 'div' and self.callout_depth:
            self.callout_depth += 1
        if self.callout_depth:
            if tag == 'br' and self.cur: self.cur[1].append('\n')
            return
        if tag in ('h1', 'h2', 'h3', 'li'):
            self.start(tag)
        elif tag == 'p':
            self.start('updated' if 'updated' in cls else 'p')
        elif tag == 'tr':
            self.flush(); self.row = []
        elif tag in ('td', 'th') and self.row is not None:
            self.cell = []
        elif tag == 'br' and self.cur:
            self.cur[1].append('\n')

    def handle_endtag(self, tag):
        if not self.inside:
            return
        if tag == 'main':
            self.flush(); self.inside = False; return
        if self.callout_depth:
            if tag == 'div':
                self.callout_depth -= 1
                if self.callout_depth == 0:
                    self.flush(); self.callout_depth = None
            return
        if tag in ('h1', 'h2', 'h3', 'li', 'p'):
            self.flush()
        elif tag in ('td', 'th') and self.cell is not None:
            self.row.append(re.sub(r'\s+', ' ', ''.join(self.cell)).strip()); self.cell = None
        elif tag == 'tr' and self.row is not None:
            if self.row and not getattr(self, 'header_done', False):
                self.header = self.row; self.header_done = True     # first row = column titles
            elif self.row:
                self.blocks.append({'t': 'row', 'cells': self.row, 'heads': getattr(self, 'header', [])})
            self.row = None
        elif tag == 'table':
            self.header_done = False

    def handle_data(self, data):
        if not self.inside:
            return
        data = data.replace('\n', ' ')   # source line breaks are just spaces; only <br> breaks a line
        if self.cell is not None:
            self.cell.append(data)
        elif self.cur:
            self.cur[1].append(data)

def parse(path):
    p = Legal()
    p.feed(open(path, encoding='utf-8').read())
    p.flush()
    return p.blocks

site = sys.argv[1]
docs = {'privacy': parse(os.path.join(site, 'privacy.html')), 'terms': parse(os.path.join(site, 'terms.html'))}
for k, b in docs.items():
    assert b and b[0]['t'] == 'h1', f'{k}: page structure not recognised'
out = ["// GENERATED by tools/sync-legal.py from the website's privacy.html and terms.html — do not edit by hand.",
       "export type LegalBlock = { t: 'h1' | 'updated' | 'h2' | 'h3' | 'p' | 'li' | 'callout'; text: string } | { t: 'row'; cells: string[]; heads: string[] };",
       ""]
for k, b in docs.items():
    out.append(f"export const {k}: LegalBlock[] = {json.dumps(b, ensure_ascii=False, indent=1)};")
    out.append('')
dest = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'lib', 'legal-data.ts')
open(dest, 'w', encoding='utf-8').write('\n'.join(out))
print('wrote', dest, {k: len(v) for k, v in docs.items()})
