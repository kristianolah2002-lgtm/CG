#!/usr/bin/env python3
"""Builds the translations for the website (i18n-data.js) and, if the app folder is given, the app
(src/lib/i18n-data.ts) from tools/i18n/*.tsv (key, de, es, fr) and tools/i18n/patterns.py.
Usage: python3 tools/build-i18n.py [path/to/app]"""
import glob, json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
sys.path.insert(0, os.path.join(here, 'i18n'))
from patterns import P  # noqa: E402

dict_ = {}
problems = []
for path in sorted(glob.glob(os.path.join(here, 'i18n', '*.tsv'))):
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        cols = line.split('\t')
        if len(cols) != 4 or not all(c.strip() for c in cols):
            problems.append(f'{os.path.basename(path)}:{n}: needs 4 filled columns: {line[:80]}')
            continue
        key = re.sub(r'\s+', ' ', cols[0]).strip()
        tr = [c.strip() for c in cols[1:]]
        if key in dict_ and dict_[key] != tr:
            problems.append(f'{os.path.basename(path)}:{n}: "{key[:60]}" is translated twice, differently')
            continue
        # HTML blocks must keep the same tags
        tags = sorted(re.findall(r'<[^>]+>', key))
        for t in tr:
            if sorted(re.findall(r'<[^>]+>', t)) != tags:
                problems.append(f'{os.path.basename(path)}:{n}: tags differ in "{t[:60]}"')
        dict_[key] = tr
pats = []
for p in P:
    if len(p) != 4:
        problems.append(f'pattern needs 4 parts: {p[0]}')
        continue
    src = p[0]
    groups = re.compile(src.replace(r'\p{Lu}', 'A').replace(r'\p{L}', 'a')).groups
    for t in p[1:]:
        for g in re.findall(r'\$(\d)|\{(\d)\}', t):
            k = int(g[0] or g[1])
            if k > groups:
                problems.append(f'pattern {src}: uses ${k} but has {groups} groups')
    pats.append(list(p))
if problems:
    print('\n'.join(problems))
    sys.exit(1)
# Website: one small file per language (only the chosen language is downloaded)
os.makedirs(os.path.join(root, 'i18n'), exist_ok=True)
for i, lang in enumerate(['de', 'es', 'fr']):
    data = {'dict': {k: v[i] for k, v in dict_.items()}, 'patterns': [[p[0], p[1 + i]] for p in pats]}
    with open(os.path.join(root, 'i18n', f'{lang}.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build-i18n.py from tools/i18n/ — do not edit by hand. */\nwindow.CG_I18N_DATA = '
                + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'website: {len(dict_)} texts, {len(pats)} patterns')
data = {'dict': dict_, 'patterns': [[p[0], p[1:]] for p in pats]}
blob = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
if len(sys.argv) > 1:
    app = sys.argv[1]
    with open(os.path.join(app, 'src', 'lib', 'i18n-data.ts'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by the website\'s tools/build-i18n.py — do not edit by hand. */\n'
                'export const I18N_DATA: { dict: Record<string, string[]>; patterns: [string, string[]][] } = ' + blob + ';\n')
    print('app: written')
