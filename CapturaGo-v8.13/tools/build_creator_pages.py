"""Real pages for every creator (for Google and for link previews), generated from the public listings and reviews.

  /p/<handle>.html  the page Google indexes (in sitemap.xml). "Book" opens the profile at the normal service fee.
  /c/<handle>.html  the creator's own link (what they share). Same page, a rich WhatsApp/Instagram preview, but
                    "noindex" with the canonical pointing to /p/<handle> — and "Book" keeps the lower link fee.

Run before uploading the website (needs internet):   python3 tools/build_creator_pages.py
Offline / testing:                                   python3 tools/build_creator_pages.py --json data.json
(data.json = {"photographers": [...], "reviews": [...]} with the same fields as the database.)
Only reads what any visitor can see (the public anon key). Pages of creators who left are removed."""
import glob, html, json, os, re, sys, urllib.error, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://capturago.com'
MARK = '<!-- generated by tools/build_creator_pages.py -->'
HANDLE_RE = re.compile(r'^[a-z0-9][a-z0-9-]{1,28}[a-z0-9]$')
e = lambda s: html.escape(str(s if s is not None else ''), quote=True)

def config():
    src = open(os.path.join(ROOT, 'supabase.js'), encoding='utf-8').read()
    url = re.search(r"const SUPABASE_URL = '([^']+)'", src).group(1)
    key = re.search(r"const SUPABASE_ANON_KEY = '([^']+)'", src).group(1)
    return url, key

def fetch(url, key, path):
    req = urllib.request.Request(f'{url}/rest/v1/{path}', headers={'apikey': key, 'Authorization': f'Bearer {key}', 'Accept': 'application/json'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode('utf-8'))

def load_live():
    url, key = config()
    cols = ['id', 'name', 'handle', 'city', 'description', 'services', 'occasions', 'vibes', 'languages', 'cover_image_url', 'gallery',
            'packages', 'rating', 'reviews_count', 'verified', 'available', 'payouts_enabled', 'created_at', 'completed_shoots']
    listings = None
    for drop in ([], ['completed_shoots'], ['completed_shoots', 'occasions', 'vibes']):   # older databases lack newer columns
        try:
            listings = fetch(url, key, f"photographers?select={','.join(c for c in cols if c not in drop)}&handle=not.is.null&limit=5000")
            break
        except urllib.error.HTTPError as err:
            if err.code != 400: raise
    reviews = None
    for c in ('id,photographer_id,reviewer_name,rating,comment,created_at,booking_id,reply', 'id,photographer_id,reviewer_name,rating,comment,created_at,booking_id'):
        try:
            reviews = fetch(url, key, f'reviews?select={c}&order=created_at.desc&limit=20000'); break
        except urllib.error.HTTPError as err:
            if err.code != 400: raise
    return listings or [], reviews or []

def labels():
    """Service / occasion / vibe labels from taxonomy.js (the website's own list)."""
    src = open(os.path.join(ROOT, 'taxonomy.js'), encoding='utf-8').read()
    return {m.group(1): m.group(2) for m in re.finditer(r"\{\s*id:\s*'([a-z_]+)'.*?label:\s*'((?:[^'\\]|\\.)*)'", src)}

def https(u):
    u = str(u or '').strip()
    return u if re.match(r'^https://[^\s"<>]+$', u) else ''

def money(v):
    try: n = float(v)
    except (TypeError, ValueError): return ''
    return f'€{n:.0f}' if n == int(n) else f'€{n:.2f}'

def city_slugs():
    return {os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(ROOT, 'in', '*.html'))}

def slugify(s):
    return re.sub(r'[^a-z0-9]+', '-', str(s or '').split(',')[0].strip().lower()).strip('-')

def page(p, revs, kind, LAB, cities):
    h = p['handle']; first = str(p.get('name') or '').split(' ')[0] or 'this creator'
    city = str(p.get('city') or '').strip(); city1 = city.split(',')[0].strip()
    svcs = [LAB.get(s, s) for s in (p.get('services') or []) if isinstance(s, str)]
    role = svcs[0] if svcs else 'Creator'
    title = f"{p['name']} — {role} in {city1}" if city1 else f"{p['name']} — {role}"
    desc_src = re.sub(r'\s+', ' ', str(p.get('description') or '')).strip()
    desc = (desc_src[:152] + '…') if len(desc_src) > 155 else (desc_src or f"Book {p['name']}, {role.lower()} in {city1 or 'your destination'}, on CapturaGo — protected payment, verified reviews.")
    canon = f'{SITE}/p/{h}'
    cover = https(p.get('cover_image_url')) or next((https(g.get('url')) for g in (p.get('gallery') or []) if isinstance(g, dict) and https(g.get('url'))), '') or f'{SITE}/images/og-cover.jpg'
    # Book: /c/ keeps the creator's own link (lower fee); /p/ (search) opens the profile at the normal fee
    book = f'/?handle={h}' if kind == 'c' else f"/?creator={p['id']}"
    rating = float(p.get('rating') or 0); count = int(p.get('reviews_count') or 0)
    pk = [k for k in (p.get('packages') or []) if isinstance(k, dict) and k.get('name') and k.get('price_eur') not in (None, '')]
    gal = [g for g in (p.get('gallery') or []) if isinstance(g, dict) and https(g.get('url'))][:9]
    shown = [r for r in revs if r.get('comment') or r.get('reply')][:10]
    ld = {'@context': 'https://schema.org', '@type': 'ProfessionalService', 'name': p['name'], 'url': canon, 'image': cover, 'description': desc,
          **({'address': {'@type': 'PostalAddress', 'addressLocality': city1}} if city1 else {}),
          **({'aggregateRating': {'@type': 'AggregateRating', 'ratingValue': round(rating, 1), 'reviewCount': count, 'bestRating': 5, 'worstRating': 1}} if count > 0 and rating > 0 else {}),
          **({'review': [{'@type': 'Review', 'author': {'@type': 'Person', 'name': r.get('reviewer_name') or 'Traveller'}, 'datePublished': str(r.get('created_at') or '')[:10],
                          'reviewRating': {'@type': 'Rating', 'ratingValue': int(r.get('rating') or 0), 'bestRating': 5}, **({'reviewBody': r['comment']} if r.get('comment') else {})} for r in shown[:5]]} if shown else {}),
          **({'makesOffer': [{'@type': 'Offer', 'name': k['name'], 'price': f"{float(k['price_eur']):.2f}", 'priceCurrency': 'EUR'} for k in pk[:8]]} if pk else {})}
    crumbs = {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
        {'@type': 'ListItem', 'position': 1, 'name': 'CapturaGo', 'item': SITE + '/'},
        *([{'@type': 'ListItem', 'position': 2, 'name': f'Creators in {city1}', 'item': f'{SITE}/in/{slugify(city1)}'}] if slugify(city1) in cities else []),
        {'@type': 'ListItem', 'position': 3 if slugify(city1) in cities else 2, 'name': p['name'], 'item': canon}]}
    jsonld = lambda o: json.dumps(o, ensure_ascii=False).replace('</', '<\\/')
    stars = lambda n: '★' * max(0, min(5, int(round(float(n or 0))))) + '☆' * (5 - max(0, min(5, int(round(float(n or 0))))))
    robots = f'<meta name="robots" content="noindex, follow" />\n  <link rel="canonical" href="{canon}" />' if kind == 'c' else f'<link rel="canonical" href="{canon}" />'
    paused = p.get('available') is False
    meta_line = ' · '.join(x for x in [
        f'⭐ {rating:.1f} ({count} review{"s" if count != 1 else ""})' if count > 0 and rating > 0 else 'New on CapturaGo',
        f"📸 {int(p['completed_shoots'])} completed shoot{'s' if int(p['completed_shoots']) != 1 else ''}" if int(p.get('completed_shoots') or 0) > 0 else '',
        f"🗣 {e(p['languages'])}" if p.get('languages') else ''] if x)
    # sections (built separately: f-strings can't nest quotes with backslashes before Python 3.12)
    about = f'<section class="cp-about"><h2>About {e(first)}</h2><p translate="no">{e(desc_src)}</p></section>' if desc_src else ''
    gallery = ''
    if gal:
        imgs = ''.join('<a href="' + e(book) + '"><img src="' + e(https(g.get('thumb')) or https(g.get('url'))) + '" alt="Photo by ' + e(p['name']) + '" loading="lazy" width="400" height="400" /></a>' for g in gal)
        gallery = '<section class="cp-gallery" aria-label="Portfolio"><h2>Portfolio</h2><div class="cp-grid">' + imgs + '</div></section>'
    packages = ''
    if pk:
        rows = ''
        for k in pk:
            rows += ('<div class="cp-pkg"><div><strong translate="no">' + e(k['name']) + '</strong>'
                     + ('<span>🌐 Remote — delivered online</span>' if k.get('type') == 'delivery' else '')
                     + ('<p translate="no">' + e(k.get('desc')) + '</p>' if k.get('desc') else '')
                     + '</div><span class="cp-price">' + money(k['price_eur']) + '</span></div>')
        packages = ('<section class="cp-packages"><h2>Packages</h2>' + rows + '<p class="muted small">🔒 You pay securely on CapturaGo; the money is only released to '
                    + e(first) + ' after your shoot.</p></section>')
    reviews_html = ''
    if shown:
        rows = ''
        for r in shown:
            n = int(r.get('rating') or 0)
            rows += ('<div class="review-item"><div class="review-header"><strong translate="no">' + e(r.get('reviewer_name') or 'Traveller') + '</strong>'
                     + ('<span class="verified-tag">✓ Verified booking</span>' if r.get('booking_id') else '')
                     + '<span class="stars-inline" aria-label="' + str(n) + ' out of 5">' + stars(n) + '</span>'
                     + '<span class="muted small">' + e(str(r.get('created_at') or '')[:10]) + '</span></div>'
                     + ('<p translate="no">' + e(r.get('comment')) + '</p>' if r.get('comment') else '')
                     + ('<div class="review-reply"><div class="review-reply-head"><strong>↩ Reply from ' + e(first) + '</strong></div><p translate="no">' + e(r.get('reply')) + '</p></div>' if r.get('reply') else '')
                     + '</div>')
        reviews_html = '<section class="cp-reviews"><h2>Reviews</h2>' + rows + '</section>'
    more_city = ('<a class="secondary-btn" href="/in/' + slugify(city1) + '" style="text-decoration:none">More creators in ' + e(city1) + '</a>') if slugify(city1) in cities else ''
    cta1 = ('See ' + e(first) + '’s profile') if paused else ('Book ' + e(first))
    cta2 = ('See ' + e(first) + '’s profile') if paused else ('Check ' + e(first) + '’s free days')
    paused_html = '<p class="cp-paused">Not taking bookings right now — open the profile to get notified when they are.</p>' if paused else ''
    out = f"""<!DOCTYPE html>
{MARK}
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <script src="/i18n.js"></script>
  <title>{e(title)} | CapturaGo</title>
  <meta name="description" content="{e(desc)}" />
  {robots}
  <meta property="og:type" content="profile" />
  <meta property="og:title" content="{e(title)}" />
  <meta property="og:description" content="{e(desc)}" />
  <meta property="og:url" content="{SITE}/{kind}/{h}" />
  <meta property="og:image" content="{e(cover)}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="theme-color" content="#211911" />
  <link rel="icon" href="/favicon.ico" sizes="any" />
  <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
  <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
  <link rel="stylesheet" href="/fonts/fonts.css" />
  <link rel="stylesheet" href="/style.css" />
  <script type="application/ld+json">{jsonld(ld)}</script>
  <script type="application/ld+json">{jsonld(crumbs)}</script>
</head>
<body class="page-simple creator-page">
<script src="/consent.js"></script>
<nav class="simple-nav">
  <a href="/" class="logo">✦ CapturaGo</a>
  <a href="/#portfolio-section" class="back">Browse creators →</a>
</nav>
<main class="landing cp">
  <section class="cp-hero">
    <img class="cp-cover" src="{e(cover)}" alt="{e(p['name'])}" width="1200" height="800" fetchpriority="high" />
    <div class="cp-head">
      <div class="section-eyebrow">{e(' · '.join(svcs[:3]) or 'Creator')}{(' · 📍 ' + e(city)) if city else ''}</div>
      <h1 translate="no">{e(p['name'])}</h1>
      <p class="cp-meta">{meta_line}</p>
      {paused_html}
      <div class="landing-cta"><a class="primary-btn" href="{e(book)}" style="text-decoration:none">{cta1}</a>
        <a class="secondary-btn" href="{e(book)}" style="text-decoration:none">Message {e(first)}</a></div>
    </div>
  </section>
  {about}
  {gallery}
  {packages}
  {reviews_html}
  <div class="landing-cta"><a class="primary-btn" href="{e(book)}" style="text-decoration:none">{cta2}</a>
    {more_city}</div>
</main>
<footer class="footer"><div class="footer-inner"><p>© 2026 CapturaGo · <a href="/privacy.html">Privacy</a> · <a href="/terms.html">Terms</a></p></div></footer>
</body>
</html>
"""
    return out

def build(listings, reviews):
    LAB, cities = labels(), city_slugs()
    by = {}
    for r in reviews or []:
        if isinstance(r, dict) and r.get('photographer_id'): by.setdefault(r['photographer_id'], []).append(r)
    made = set()
    for p in listings or []:
        if not isinstance(p, dict) or not p.get('id') or not str(p.get('name') or '').strip(): continue
        h = str(p.get('handle') or '').lower()
        if not HANDLE_RE.match(h) or p.get('hidden') or str(p['id']).startswith('ex-'): continue
        p['handle'] = h
        revs = sorted(by.get(p['id'], []), key=lambda r: str(r.get('created_at') or ''), reverse=True)
        for kind in ('p', 'c'):
            os.makedirs(os.path.join(ROOT, kind), exist_ok=True)
            open(os.path.join(ROOT, kind, f'{h}.html'), 'w', encoding='utf-8').write(page(p, revs, kind, LAB, cities))
        made.add(h)
    removed = 0
    for kind in ('p', 'c'):   # creators who left (or changed their link): their old generated pages go
        for f in glob.glob(os.path.join(ROOT, kind, '*.html')):
            if os.path.splitext(os.path.basename(f))[0] not in made and MARK in open(f, encoding='utf-8').read(400):
                os.remove(f); removed += 1
    # sitemap: everything else stays as tools/build_pages.py wrote it; the /p/ pages are replaced
    sm_path = os.path.join(ROOT, 'sitemap.xml')
    sm = open(sm_path, encoding='utf-8').read() if os.path.exists(sm_path) else '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</urlset>\n'
    sm = re.sub(rf'  <url><loc>{re.escape(SITE)}/p/[^<]*</loc></url>\n', '', sm)
    sm = sm.replace('</urlset>', ''.join(f'  <url><loc>{SITE}/p/{h}</loc></url>\n' for h in sorted(made)) + '</urlset>')
    open(sm_path, 'w', encoding='utf-8').write(sm)
    return made, removed

if __name__ == '__main__':
    if '--json' in sys.argv:
        d = json.load(open(sys.argv[sys.argv.index('--json') + 1], encoding='utf-8'))
        listings, reviews = d.get('photographers', []), d.get('reviews', [])
    else:
        listings, reviews = load_live()
    made, removed = build(listings, reviews)
    print(f'creator pages: {len(made)} creators (/p/ and /c/), {removed} old pages removed, sitemap updated')
